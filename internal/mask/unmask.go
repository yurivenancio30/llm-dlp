// Unmask: swaps the pseudonyms back, including in a response that arrives in chunks.

// Table is the pseudonym -> real "from:to" of ONE request. It lives only in memory: it is built
// while the request is masked and used to unmask the response.
//
// Finding the pseudonyms in a text uses an index by the start (first 4 bytes -> possible lengths)
// and then a direct lookup in the map. The cost depends on the size of the text, not on how many
// pseudonyms there are: with an alternation regex, 5 thousand distinct pseudonyms (a CSV of e-mails
// in the conversation) already took seconds.
type Table struct {
	m        map[string]string
	typ      map[string]string    // pseudonym -> type (who wrote it: see decision.go)
	pfx      map[uint32][]int32   // first 4 bytes -> lengths, from longest to shortest
	pair     [1 << 16 / 64]uint64 // filter: does any pseudonym start with these 2 bytes?
	start    map[string]bool      // starts of 1 to 3 bytes (to know whether the end of a text may be a cut pseudonym)
	shorts   []string             // pseudonyms shorter than 4 bytes (there should be none)
	maxLen   int
	ipPrefix map[string]string // "240.a.b" -> "10.42.7"
	// Conflicts: pseudonyms that collided and so will not be unmasked (for the log).
	Conflicts int
	collided  []string // the pseudonyms (or fake IP prefixes) that collided, up to 20

	muNotUndone sync.Mutex
	nd          []string // our pseudonyms left over on the way back (see NotUndone)
}

// reLeftover: the pseudonym shapes, in any case, that may be left over on the way back: label
// ("CPF-x", "Sensivel-x"), person, object ("t_x"), e-mail and host (.invalid) and fake IP.
var reLeftover = regexp.MustCompile(`[A-Za-z][A-Za-z:]*-[A-Za-z2-7]{8}|(?i:pessoa) [A-Za-z2-7]{8}|[A-Za-z]+_[A-Za-z2-7]{8}|[\w.+-]+\.invalid|\b2(?:4\d|5[0-5])\.\d{1,3}\.\d{1,3}\.\d{1,3}\b`)

const maxNotUndone = 20

// noteLeftovers: the pseudonyms generated by llm-dlp that stayed in s after unmasking (the model
// changed the case in a way no variant covers, cut or joined a pseudonym, or cited one from another
// conversation). An IP in the fake range counts too: no real data uses 240.0.0.0/4.
func (t *Table) noteLeftovers(s string) {
	if !strings.ContainsAny(s, "-_.") && !strings.Contains(s, "essoa") && !strings.Contains(s, "ESSOA") {
		return
	}
	for _, v := range reLeftover.FindAllString(s, -1) {
		ours := false
		if a, err := netip.ParseAddr(v); err == nil {
			ours = fakeNet.Contains(a)
		} else {
			_, ours = generatedPseudos.Load(strings.ToLower(v))
		}
		if !ours {
			continue
		}
		t.muNotUndone.Lock()
		if len(t.nd) < maxNotUndone && !slices.Contains(t.nd, v) {
			t.nd = append(t.nd, v)
		}
		t.muNotUndone.Unlock()
	}
}

// NotUndone: the pseudonyms left over in the responses unmasked with this table (up to 20). A
// pseudonym is not real data: it can go to the log.
func (t *Table) NotUndone() []string {
	t.muNotUndone.Lock()
	defer t.muNotUndone.Unlock()
	return slices.Clone(t.nd)
}

// Collided: the pseudonyms that two different real values got in this table (up to 20; a fake IP
// shows as "240.a.b.x", the whole /24 network). A pseudonym is not real data: it can go to the log,
// and its shape gives the type.
func (t *Table) Collided() []string { return t.collided }

var reFakeIP = regexp.MustCompile(`\b(2(?:4\d|5[0-5])\.\d{1,3}\.\d{1,3})\.(\d{1,3})\b`)

func NewTable(entries []Entry) *Table {
	t := &Table{m: map[string]string{}, typ: map[string]string{}, pfx: map[uint32][]int32{}, start: map[string]bool{}, ipPrefix: map[string]string{}}
	// Collision (two real values with the same pseudonym — rare, but possible, mostly in the fake
	// IP subnet): unmasking would pick one of the two and could, e.g., point a command at the wrong
	// host. In those cases the pseudonym is left masked.
	conflict, conflictIP := map[string]bool{}, map[string]bool{}
	// first the pseudonyms as they went out, then the ones the model wrote in another case (an
	// assistant text resent as the API sent it): the variant of one spelling never takes the place
	// of another one's pseudonym
	ord := make([]Entry, 0, len(entries))
	var others []Entry
	for _, e := range entries {
		if primaryCase(e.Pseudo, e.Real, e.Type) {
			ord = append(ord, e)
		} else {
			others = append(others, e)
		}
	}
	nPrimary := len(ord)
	ord = append(ord, others...)
	var base []Entry // one per pseudonym, for the case variants
	for k, e := range ord {
		if _, ok := t.m[e.Pseudo]; ok && k >= nPrimary {
			continue // case variant that matches an already registered pseudonym
		}
		if r, ok := t.m[e.Pseudo]; ok {
			// the same number with other punctuation ("12.345.678-9" and "123456789") is not a
			// collision: it is the same value. The first spelling seen stays. Nor is the same
			// person pseudonym for two names a collision: the people registry gives the person's id
			// to the full name and to first + last ("Maria Fernanda Silva" and "Maria Silva"), and
			// both spellings are the same person.
			if r != e.Real && e.Type != "nome" && !sameValue(e.Type, r, e.Real) {
				conflict[e.Pseudo] = true
			}
			continue
		}
		t.m[e.Pseudo] = e.Real
		t.typ[e.Pseudo] = e.Type
		if e.Type == "nome" || pseudoWithCase(e.Type) {
			base = append(base, e)
		}
		if reFakeIP.MatchString(e.Pseudo) && strings.Count(e.Pseudo, ".") == 3 && strings.Count(e.Real, ".") == 3 {
			f, r := e.Pseudo[:strings.LastIndex(e.Pseudo, ".")], e.Real[:strings.LastIndex(e.Real, ".")]
			if current, ok := t.ipPrefix[f]; ok && current != r {
				conflictIP[f] = true
			}
			t.ipPrefix[f] = r
		}
	}
	// the other cases of the pseudonym (of a person, an object, a labeled type), after all the
	// spellings that appeared: the variant never takes the place of a real spelling ("Maria da
	// Silva" and "propostas" stay as they were)
	for _, e := range base {
		if conflict[e.Pseudo] {
			continue
		}
		var vs []Entry
		if e.Type == "nome" {
			vs = nameVariants(e.Pseudo, e.Real)
		} else {
			vs = caseVariants(e.Pseudo, e.Real, e.Type, t.m)
		}
		for _, v := range vs {
			if _, ok := t.m[v.Pseudo]; !ok {
				t.m[v.Pseudo], t.typ[v.Pseudo] = v.Real, v.Type
			}
		}
	}
	for p := range conflict {
		delete(t.m, p)
	}
	for f := range conflictIP {
		delete(t.ipPrefix, f)
		for p := range t.m {
			if strings.HasPrefix(p, f+".") {
				delete(t.m, p)
			}
		}
	}
	t.Conflicts = len(conflict) + len(conflictIP)
	for p := range conflict {
		t.collided = append(t.collided, p)
	}
	for f := range conflictIP {
		t.collided = append(t.collided, f+".x")
	}
	sort.Strings(t.collided)
	if len(t.collided) > maxNotUndone {
		t.collided = t.collided[:maxNotUndone]
	}
	for k := range t.m {
		if len(k) > t.maxLen {
			t.maxLen = len(k)
		}
		if len(k) < 4 {
			t.shorts = append(t.shorts, k)
			continue
		}
		for l := 1; l <= 3; l++ {
			t.start[k[:l]] = true
		}
		c := uint32(k[0])<<24 | uint32(k[1])<<16 | uint32(k[2])<<8 | uint32(k[3])
		has := false
		for _, n := range t.pfx[c] {
			if int(n) == len(k) {
				has = true
				break
			}
		}
		if !has {
			t.pfx[c] = append(t.pfx[c], int32(len(k)))
		}
		t.pair[c>>22] |= 1 << (c >> 16 & 63)
	}
	for _, ns := range t.pfx {
		sort.Slice(ns, func(i, j int) bool { return ns[i] > ns[j] })
	}
	sort.Slice(t.shorts, func(i, j int) bool { return len(t.shorts[i]) > len(t.shorts[j]) })
	return t
}

// primaryCase: the pseudonym has the case it is generated with for this spelling (and is not a case
// variant). Object (pseudoObject): lowercase for a lowercase name, uppercase prefix and lowercase
// ID for an uppercase name, prefix with the first letter uppercase for mixed case. Labeled type:
// the pseudoLabel shape. The other types have no variant.
func primaryCase(ps, real, typ string) bool {
	if !pseudoWithCase(typ) {
		return true
	}
	i := strings.LastIndexByte(ps, pseudoSep(typ))
	if i <= 0 {
		return true
	}
	pfx, id := ps[:i], ps[i+1:]
	if !isObject(typ) {
		return primaryLabel(pfx, id, real)
	}
	switch {
	case strings.ToLower(real) == real:
		return ps == strings.ToLower(ps)
	case strings.ToUpper(real) == real:
		return pfx == strings.ToUpper(pfx) && id == strings.ToLower(id)
	}
	return pfx == pfx[:1]+strings.ToLower(pfx[1:]) && pfx[:1] == strings.ToUpper(pfx[:1]) && id != strings.ToLower(id)
}

// matched returns the end of the longest pseudonym that starts at s[i], or -1.
func (t *Table) matched(s string, i int) int {
	if i+4 <= len(s) {
		k2 := uint32(s[i])<<8 | uint32(s[i+1])
		if t.pair[k2>>6]&(1<<(k2&63)) != 0 {
			for _, n := range t.pfx[k2<<16|uint32(s[i+2])<<8|uint32(s[i+3])] {
				if end := i + int(n); end <= len(s) {
					if _, ok := t.m[s[i:end]]; ok {
						return end
					}
				}
			}
		}
	}
	for _, k := range t.shorts {
		if strings.HasPrefix(s[i:], k) {
			return i + len(k)
		}
	}
	return -1
}

// scan calls fn for each pseudonym in s, left to right, without overlap.
func (t *Table) scan(s string, fn func(ini, end int)) {
	for i := 0; i < len(s); {
		if end := t.matched(s, i); end > 0 {
			fn(i, end)
			i = end
		} else {
			i++
		}
	}
}

// sameValue: are a and b the same value written two ways ("João Silva" and "JOAO SILVA",
// "12.345.678-9" and "123456789")? Follows the same normalization used to generate the pseudonym.
func sameValue(typ, a, b string) bool {
	if isObject(typ) {
		ent := strings.TrimPrefix(typ, objTypePrefix)
		return normObj(ent, a) == normObj(ent, b)
	}
	switch typ {
	case "segredo", "ip":
		return false
	case "email", "host", "pix", "dominio":
		return strings.EqualFold(a, b)
	case "cpf", "cnpj", "pis", "cnh", "telefone", "cep", "cartao", "rg", "conta":
		return canonNum(a) == canonNum(b)
	}
	return NormName(a) == NormName(b)
}

func (t *Table) Empty() bool { return len(t.m) == 0 }

// Unmask swaps pseudonyms for real values. With json=true, the real value is escaped to fit inside
// a JSON string (used in input_json_delta).
func (t *Table) Unmask(s string, inJSON bool) string {
	if t.Empty() {
		return s
	}
	esc := func(v string) string {
		if !inJSON {
			return v
		}
		b, _ := json.Marshal(v)
		return string(b[1 : len(b)-1])
	}
	var b strings.Builder
	lastPos := 0
	t.scan(s, func(ini, end int) {
		b.WriteString(s[lastPos:ini])
		b.WriteString(esc(t.m[s[ini:end]]))
		lastPos = end
	})
	if lastPos > 0 {
		b.WriteString(s[lastPos:])
		s = b.String()
	}
	if len(t.ipPrefix) > 0 {
		// other addresses in the same fake subnet (e.g. 240.a.b.0/24 written by the model)
		s = reFakeIP.ReplaceAllStringFunc(s, func(ip string) string {
			k := ip[:strings.LastIndex(ip, ".")]
			if r, ok := t.ipPrefix[k]; ok {
				return r + ip[strings.LastIndex(ip, "."):]
			}
			return ip
		})
	}
	t.noteLeftovers(s)
	return s
}

// hold: how many bytes at the end of s may be the start of a pseudonym.
func (t *Table) hold(s string) int {
	max := t.maxLen - 1
	if max > len(s) {
		max = len(s)
	}
	for l := max; l > 0; l-- {
		if t.canBeStart(s[len(s)-l:]) {
			return l
		}
	}
	if len(t.ipPrefix) > 0 { // end of text resembling the start of a fake IP: "24", "240.1", ...
		i := len(s)
		for i > 0 && (isDig(s[i-1]) || s[i-1] == '.') && len(s)-i < 16 {
			i--
		}
		if i < len(s) && s[i] == '2' && (i == 0 || !isDig(s[i-1])) {
			return len(s) - i
		}
	}
	return 0
}

// canBeStart: may c be the start of a still incomplete pseudonym? For 4 bytes or more the answer is
// approximate (it only looks at the start and the length): it may hold back a text that in the end
// was not a pseudonym, and it is delivered in the next chunk.
func (t *Table) canBeStart(c string) bool {
	for _, k := range t.shorts {
		if len(c) < len(k) && strings.HasPrefix(k, c) {
			return true
		}
	}
	if len(c) < 4 {
		return t.start[c]
	}
	for _, n := range t.pfx[uint32(c[0])<<24|uint32(c[1])<<16|uint32(c[2])<<8|uint32(c[3])] {
		if int(n) > len(c) {
			return true
		}
	}
	return false
}

// Stream unmasks a text that arrives in chunks, never delivering a cut pseudonym.
type Stream struct {
	t      *Table
	inJSON bool
	buf    string
}

func (t *Table) NewStream(inJSON bool) *Stream { return &Stream{t: t, inJSON: inJSON} }

// Push receives a chunk and returns what can already be delivered (unmasked).
func (f *Stream) Push(piece string) string {
	if f.t.Empty() {
		return piece
	}
	f.buf += piece
	// It may only hold back AFTER the last complete pseudonym; otherwise the end of a complete
	// pseudonym (e.g. "...x2") could be taken for the start of another (e.g. IP "2..") and the
	// complete pseudonym would be cut in half.
	fullEnd := 0
	f.t.scan(f.buf, func(_, end int) { fullEnd = end })
	if len(f.t.ipPrefix) > 0 {
		if ms := reFakeIP.FindAllStringIndex(f.buf, -1); len(ms) > 0 && ms[len(ms)-1][1] > fullEnd &&
			ms[len(ms)-1][1] < len(f.buf) { // a finished fake IP (something after it) is also complete
			fullEnd = ms[len(ms)-1][1]
		}
	}
	k := f.t.hold(f.buf[fullEnd:])
	ready := f.buf[:len(f.buf)-k]
	f.buf = f.buf[len(f.buf)-k:]
	return f.t.Unmask(ready, f.inJSON)
}

// Close delivers what is left at the end of the block.
func (f *Stream) Close() string {
	r := f.t.Unmask(f.buf, f.inJSON)
	f.buf = ""
	return r
}
